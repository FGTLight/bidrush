/**
 * Database schema. Column names are snake_case in Postgres (see `casing` in
 * db/client.ts and drizzle.config.ts).
 *
 * Invariants that protect money-like data are enforced by Postgres itself
 * (CHECKs, unique indexes and the triggers in the hand-written migration),
 * so no code path, bug or concurrent request can break them.
 */
import { sql } from 'drizzle-orm'
import {
  bigint,
  boolean,
  check,
  doublePrecision,
  jsonb,
  index,
  integer,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core'

const createdAt = () => timestamp({ withTimezone: true }).notNull().defaultNow()

// ---------------------------------------------------------------- users

export const userRole = pgEnum('user_role', ['user', 'admin'])

export const users = pgTable(
  'users',
  {
    id: uuid().primaryKey().defaultRandom(),
    email: text().notNull(),
    passwordHash: text().notNull(),
    displayName: text().notNull(),
    role: userRole().notNull().default('user'),
    /** Set by an admin (or the anti-bot engine); blocked users can't bid. */
    blockedAt: timestamp({ withTimezone: true }),
    createdAt: createdAt(),
  },
  (t) => [
    unique('users_email_key').on(t.email),
    check('users_email_lowercase', sql`${t.email} = lower(${t.email})`),
  ],
)

/**
 * Server-side record of each sign-in. The JWT in the cookie names its
 * session, so signing out (or blocking a user) revokes it immediately
 * instead of waiting for the token to expire.
 */
export const sessions = pgTable(
  'sessions',
  {
    id: uuid().primaryKey().defaultRandom(),
    userId: uuid()
      .notNull()
      .references(() => users.id),
    createdAt: createdAt(),
    expiresAt: timestamp({ withTimezone: true }).notNull(),
    revokedAt: timestamp({ withTimezone: true }),
    ip: text(),
    userAgent: text(),
  },
  (t) => [index('sessions_user_idx').on(t.userId)],
)

// ---------------------------------------------------------------- auctions

export const auctionStatus = pgEnum('auction_status', ['scheduled', 'live', 'ended', 'cancelled'])

export const auctions = pgTable(
  'auctions',
  {
    id: uuid().primaryKey().defaultRandom(),
    title: text().notNull(),
    description: text().notNull().default(''),
    imageUrl: text(),
    status: auctionStatus().notNull().default('scheduled'),
    startingPrice: integer().notNull(),
    minIncrement: integer().notNull(),
    /** Starts at `starting_price`; only ever moves up, one accepted bid at a time. */
    currentPrice: integer().notNull(),
    leaderId: uuid().references(() => users.id),
    /** The bid currently holding a credit reservation. */
    leadingBidId: uuid(),
    bidCount: integer().notNull().default(0),
    bidderCount: integer().notNull().default(0),
    startsAt: timestamp({ withTimezone: true }).notNull(),
    /** Moves forward on soft-close extensions. */
    endsAt: timestamp({ withTimezone: true }).notNull(),
    // Soft-close rules are copied onto each auction when it is created, so
    // changing the configuration never alters an auction already running.
    softCloseWindowMs: integer().notNull(),
    extensionMs: integer().notNull(),
    maxExtensionMs: integer().notNull(),
    extendedMs: integer().notNull().default(0),
    endedAt: timestamp({ withTimezone: true }),
    settledAt: timestamp({ withTimezone: true }),
    createdBy: uuid().references(() => users.id),
    createdAt: createdAt(),
  },
  (t) => [
    check('auctions_starting_price_nonneg', sql`${t.startingPrice} >= 0`),
    check('auctions_min_increment_positive', sql`${t.minIncrement} > 0`),
    check('auctions_price_not_below_start', sql`${t.currentPrice} >= ${t.startingPrice}`),
    check('auctions_ends_after_start', sql`${t.endsAt} > ${t.startsAt}`),
    check(
      'auctions_extension_within_max',
      sql`${t.extendedMs} >= 0 and ${t.extendedMs} <= ${t.maxExtensionMs}`,
    ),
    check('auctions_counts_nonneg', sql`${t.bidCount} >= 0 and ${t.bidderCount} >= 0`),
    check('auctions_leader_has_bid', sql`(${t.leaderId} is null) = (${t.leadingBidId} is null)`),
    // The scheduler polls these.
    index('auctions_status_starts_at_idx').on(t.status, t.startsAt),
    index('auctions_status_ends_at_idx').on(t.status, t.endsAt),
  ],
)

// ---------------------------------------------------------------- bids

export const bids = pgTable(
  'bids',
  {
    /** Generated by the client: the idempotency key of the bid. */
    id: uuid().primaryKey(),
    auctionId: uuid()
      .notNull()
      .references(() => auctions.id),
    userId: uuid()
      .notNull()
      .references(() => users.id),
    amount: integer().notNull(),
    /**
     * 1, 2, 3… within the auction: the auction's new `bid_count`, assigned
     * while its row is locked, so it is exactly the order bids were accepted.
     */
    seq: integer().notNull(),
    /** `clock_timestamp()`, not `now()`: real order inside one transaction. */
    createdAt: timestamp({ withTimezone: true })
      .notNull()
      .default(sql`clock_timestamp()`),
  },
  (t) => [
    check('bids_amount_positive', sql`${t.amount} > 0`),
    // Every accepted bid beats the previous price, so amounts are unique per
    // auction: a second bid at the same price can never be stored.
    uniqueIndex('bids_auction_amount_key').on(t.auctionId, t.amount),
    uniqueIndex('bids_auction_seq_key').on(t.auctionId, t.seq),
    index('bids_auction_created_idx').on(t.auctionId, t.createdAt.desc()),
    index('bids_user_created_idx').on(t.userId, t.createdAt.desc()),
  ],
)

/** One row per (auction, bidder): distinct bidder counts and "my bids". */
export const auctionParticipants = pgTable(
  'auction_participants',
  {
    auctionId: uuid()
      .notNull()
      .references(() => auctions.id),
    userId: uuid()
      .notNull()
      .references(() => users.id),
    highestBid: integer().notNull(),
    lastBidAt: timestamp({ withTimezone: true }).notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.auctionId, t.userId] }),
    index('auction_participants_user_idx').on(t.userId, t.lastBidAt.desc()),
  ],
)

// ---------------------------------------------------------------- ledger

/**
 * Double-entry credits ledger.
 *
 *   available / reserved  one pair per user
 *   issuance              system account demo credits are granted from (goes negative)
 *   revenue               system account winning bids are settled into
 *
 * Every transaction is a set of entries that sums to zero, so the whole
 * ledger always sums to zero. `balance` is a cache maintained by a trigger
 * from the entries; it exists so a CHECK can forbid negative user balances.
 */
export const ledgerAccountKind = pgEnum('ledger_account_kind', [
  'available',
  'reserved',
  'issuance',
  'revenue',
])

export const ledgerAccounts = pgTable(
  'ledger_accounts',
  {
    id: integer().primaryKey().generatedAlwaysAsIdentity(),
    userId: uuid().references(() => users.id),
    kind: ledgerAccountKind().notNull(),
    balance: bigint({ mode: 'number' }).notNull().default(0),
  },
  (t) => [
    // One account of each kind per user, and exactly one of each system account.
    unique('ledger_accounts_user_kind_key').on(t.userId, t.kind).nullsNotDistinct(),
    check(
      'ledger_accounts_owner_matches_kind',
      sql`(${t.kind} in ('issuance', 'revenue')) = (${t.userId} is null)`,
    ),
    check('ledger_accounts_balance_nonneg', sql`${t.kind} = 'issuance' or ${t.balance} >= 0`),
  ],
)

export const ledgerTxKind = pgEnum('ledger_tx_kind', ['grant', 'reserve', 'release', 'settle'])

export const ledgerTransactions = pgTable(
  'ledger_transactions',
  {
    id: bigint({ mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
    kind: ledgerTxKind().notNull(),
    auctionId: uuid().references(() => auctions.id),
    bidId: uuid(),
    memo: text(),
    createdAt: timestamp({ withTimezone: true })
      .notNull()
      .default(sql`clock_timestamp()`),
  },
  (t) => [
    // Idempotency enforced by the database: a bid is reserved and released at
    // most once, and an auction is settled at most once.
    uniqueIndex('ledger_tx_reserve_once')
      .on(t.bidId)
      .where(sql`${t.kind} = 'reserve'`),
    uniqueIndex('ledger_tx_release_once')
      .on(t.bidId)
      .where(sql`${t.kind} = 'release'`),
    uniqueIndex('ledger_tx_settle_once')
      .on(t.auctionId)
      .where(sql`${t.kind} = 'settle'`),
    check(
      'ledger_tx_refs',
      sql`${t.kind} = 'grant' or (${t.auctionId} is not null and (${t.kind} = 'settle' or ${t.bidId} is not null))`,
    ),
  ],
)

export const ledgerEntries = pgTable(
  'ledger_entries',
  {
    id: bigint({ mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
    transactionId: bigint({ mode: 'number' })
      .notNull()
      .references(() => ledgerTransactions.id),
    accountId: integer()
      .notNull()
      .references(() => ledgerAccounts.id),
    /** Signed: positive increases the account's balance. */
    amount: bigint({ mode: 'number' }).notNull(),
  },
  (t) => [
    check('ledger_entries_amount_nonzero', sql`${t.amount} <> 0`),
    index('ledger_entries_tx_idx').on(t.transactionId),
    index('ledger_entries_account_idx').on(t.accountId, t.id.desc()),
  ],
)

// ---------------------------------------------------------------- anti-bot audit trail

export const riskLevel = pgEnum('risk_level', ['allow', 'throttle', 'challenge', 'block'])

export interface StoredSignal {
  name: string
  score: number
  reason: string
}

/**
 * Every non-trivial anti-bot decision, with the signals behind it, so a
 * human can audit (and overturn) what the engine did.
 */
export const riskEvents = pgTable(
  'risk_events',
  {
    id: bigint({ mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
    userId: uuid()
      .notNull()
      .references(() => users.id),
    auctionId: uuid().references(() => auctions.id),
    bidId: uuid(),
    score: doublePrecision().notNull(),
    level: riskLevel().notNull(),
    signals: jsonb().$type<StoredSignal[]>().notNull(),
    ip: text(),
    fingerprint: text(),
    /** Set when the engine (not an admin) blocked the account. */
    autoBlocked: boolean().notNull().default(false),
    createdAt: createdAt(),
  },
  (t) => [
    check('risk_events_score_range', sql`${t.score} >= 0 and ${t.score} <= 1`),
    index('risk_events_user_created_idx').on(t.userId, t.createdAt.desc()),
    index('risk_events_created_idx').on(t.createdAt.desc()),
  ],
)

/** Latest risk per user: what the admin's flagged-users table lists. */
export const userRisk = pgTable(
  'user_risk',
  {
    userId: uuid()
      .primaryKey()
      .references(() => users.id),
    score: doublePrecision().notNull(),
    level: riskLevel().notNull(),
    topReasons: text().array().notNull(),
    lastEventAt: timestamp({ withTimezone: true }).notNull(),
    /** An admin reviewed and cleared the user; hidden until flagged again. */
    clearedAt: timestamp({ withTimezone: true }),
  },
  (t) => [index('user_risk_score_idx').on(t.score.desc())],
)
