import { z } from 'zod'

import { browserSignalsSchema, interactionSignalsSchema } from './antibot'
import { auctionSchema, bidSchema, credits, isoDate, walletSchema } from './domain'
import { bidErrorCodeSchema } from './errors'

/*
 * Every WebSocket frame is one JSON object with a `type` field. Both sides
 * validate what they receive with these schemas; nothing is trusted.
 */

// ---------------------------------------------------------------- client → server

export const helloMessage = z.object({
  type: z.literal('hello'),
  signals: browserSignalsSchema,
})

export const subscribeMessage = z.object({
  type: z.literal('subscribe'),
  auctionId: z.uuid(),
})

export const unsubscribeMessage = z.object({
  type: z.literal('unsubscribe'),
  auctionId: z.uuid(),
})

export const bidMessage = z.object({
  type: z.literal('bid'),
  /** Generated by the client; retries reuse it, so a bid is placed at most once. */
  bidId: z.uuid(),
  auctionId: z.uuid(),
  amount: credits.min(1),
  interaction: interactionSignalsSchema,
  /** Answer to a previous `challenge`, when one was issued. */
  challenge: z.object({ id: z.string().max(64), nonce: z.string().max(64) }).optional(),
})

/** Clock sync: the server answers with its own time. */
export const pingMessage = z.object({
  type: z.literal('ping'),
  clientTime: z.number(),
})

export const clientMessageSchema = z.discriminatedUnion('type', [
  helloMessage,
  subscribeMessage,
  unsubscribeMessage,
  bidMessage,
  pingMessage,
])
export type ClientMessage = z.infer<typeof clientMessageSchema>
export type BidMessage = z.infer<typeof bidMessage>

// ---------------------------------------------------------------- server → client

export const welcomeMessage = z.object({
  type: z.literal('welcome'),
  /** Null for anonymous spectators (they can watch, not bid). */
  userId: z.uuid().nullable(),
  serverTime: z.number(),
})

export const pongMessage = z.object({
  type: z.literal('pong'),
  clientTime: z.number(),
  serverTime: z.number(),
})

/** Full state, sent on subscribe and on reconnect (resync). */
export const auctionSnapshotMessage = z.object({
  type: z.literal('auction_snapshot'),
  auction: auctionSchema,
  recentBids: z.array(bidSchema).max(50),
  serverTime: z.number(),
})

/** Broadcast to every subscriber when a bid is accepted. */
export const bidPlacedMessage = z.object({
  type: z.literal('bid_placed'),
  bid: bidSchema,
  currentPrice: credits,
  bidCount: z.number().int(),
  bidderCount: z.number().int(),
  endsAt: isoDate,
  extendedMs: z.number().int(),
  /** True when this bid triggered a soft-close extension. */
  extended: z.boolean(),
})

export const auctionStartedMessage = z.object({
  type: z.literal('auction_started'),
  auction: auctionSchema,
})

export const auctionEndedMessage = z.object({
  type: z.literal('auction_ended'),
  auctionId: z.uuid(),
  winner: bidSchema.shape.bidder.nullable(),
  finalPrice: credits,
  endedAt: isoDate,
})

/** Private answer to the sender of a bid. */
export const bidAckMessage = z.discriminatedUnion('status', [
  z.object({
    type: z.literal('bid_ack'),
    status: z.literal('accepted'),
    bidId: z.uuid(),
    /** True when this bidId had already been processed (a retry). */
    duplicate: z.boolean(),
    wallet: walletSchema,
  }),
  z.object({
    type: z.literal('bid_ack'),
    status: z.literal('rejected'),
    bidId: z.uuid(),
    code: bidErrorCodeSchema,
    message: z.string(),
    /** Present with RATE_LIMITED: when the user may bid again. */
    retryAfterMs: z.number().int().optional(),
  }),
])

/** Proof-of-work the client must solve before its next bid is accepted. */
export const challengeMessage = z.object({
  type: z.literal('challenge'),
  id: z.string(),
  /** Find a nonce so that sha256(prefix + nonce) starts with `difficulty` zero hex digits. */
  prefix: z.string(),
  difficulty: z.number().int().min(1).max(8),
})

/** Pushed when another session changes this user's wallet. */
export const walletMessage = z.object({
  type: z.literal('wallet'),
  wallet: walletSchema,
})

export const errorMessage = z.object({
  type: z.literal('error'),
  code: z.string(),
  message: z.string(),
})

export const serverMessageSchema = z.union([
  welcomeMessage,
  pongMessage,
  auctionSnapshotMessage,
  bidPlacedMessage,
  auctionStartedMessage,
  auctionEndedMessage,
  bidAckMessage,
  challengeMessage,
  walletMessage,
  errorMessage,
])
export type ServerMessage = z.infer<typeof serverMessageSchema>
export type BidAck = z.infer<typeof bidAckMessage>
export type BidPlaced = z.infer<typeof bidPlacedMessage>
export type AuctionSnapshot = z.infer<typeof auctionSnapshotMessage>
